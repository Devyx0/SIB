-- ── Forecast snapshots (cache + audit) ─────────────────────────────────────────
-- One row per MSC fetch. Cache rule: reuse the newest row for a location whose
-- fetched_at is within the last hour; otherwise fetch and insert a new row.
CREATE TABLE public.weather_forecast_snapshot (
    snapshot_id             integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location                text        NOT NULL,   -- 'quebec' | 'levis'
    site_code               text        NOT NULL,   -- s0000620 | s0000416
    source                  text        NOT NULL,   -- 'msc_citypage'
    source_url              text,
    current_temp_c          numeric,
    wind_chill_c            numeric,                -- stored, not used for banding
    min_forecast_temp_24h_c numeric,
    raw                     jsonb,
    fetched_at              timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.weather_forecast_snapshot ENABLE ROW LEVEL SECURITY;

CREATE INDEX weather_snapshot_location_fetched_idx
    ON public.weather_forecast_snapshot (location, fetched_at DESC);

-- ── Evaluations (one per button click) ─────────────────────────────────────────
CREATE TABLE public.weather_evaluation (
    evaluation_id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id              integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    snapshot_id             integer     REFERENCES public.weather_forecast_snapshot(snapshot_id),
    location                text,
    band_name               text,
    suggested_tier          text,
    min_forecast_temp_24h_c numeric,
    is_critical             boolean     NOT NULL DEFAULT false,
    status                  text        NOT NULL,   -- 'ok' | 'location_unknown' | 'source_failed'
    evaluated_by            integer     REFERENCES public.employee(employee_id),
    evaluated_at            timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.weather_evaluation ENABLE ROW LEVEL SECURITY;

CREATE INDEX weather_evaluation_request_idx
    ON public.weather_evaluation (request_id, evaluated_at DESC);

COMMIT;

