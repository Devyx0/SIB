-- weather_threshold_band  — the 4 draft severity bands (data, not code).
-- weather_forecast_snapshot — one row per fetched forecast (cache + audit).
-- weather_evaluation      — one row per "Vérifier la météo" click, linked to a snapshot.
--
-- No urgency is ever written here. Accepting a suggestion goes through the
-- existing POST /requests/{id}/urgency action, which writes decision_justification_log
-- (with the weather context in after_value) and data_provenance (source_type='app').

BEGIN;

-- ── Draft severity bands ───────────────────────────────────────────────────────
-- Boundary convention: inclusive lower bound (temp_min_c), exclusive upper bound
-- (temp_max_c). NULL = unbounded on that side. So exactly -15 -> emergency,
-- -5 -> priority, +10 -> normal. suggested_tier maps onto the urgency_tier enum
-- (AJD / ajd / NULL=no change). is_critical drives the astreinte/garde badge.
CREATE TABLE public.weather_threshold_band (
    band_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text    NOT NULL,
    temp_min_c     numeric,
    temp_max_c     numeric,
    suggested_tier text,
    is_critical    boolean NOT NULL DEFAULT false,
    status         text    NOT NULL DEFAULT 'draft',
    source_text    text    NOT NULL,
    sort_order     integer NOT NULL
);

