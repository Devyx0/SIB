-- Task as first-class object: dispatch_task + request 'open' status.
-- Spec: docs/superpowers/specs/2026-10-22-task-first-class-design.md
--
-- maintenance_request  = Service Call (issue container: intake, triage, open, closed)
-- dispatch_task        = schedulable work unit, 1..n per call (assignee, due_at, status)
-- request_visit.task_id = visit now hangs off a task. Nullable here; the backfill
--   of open requests → tasks and NOT NULL enforcement land in a later migration.
--
-- Named dispatch_task to avoid colliding with vacant_unit_task / cleaning_task_*.
-- AI proposals are rows with accepted_at IS NULL (hidden from tech portal / calendar).
--
-- RLS enabled, no policies: access is through FastAPI / service_role only
-- (same pattern as request_visit, message_outbox).

-- ALTER TYPE ... ADD VALUE cannot run inside a transaction block with later use
-- of the new value, so it stays outside BEGIN/COMMIT (same as 20261021140000).
ALTER TYPE public.request_status ADD VALUE IF NOT EXISTS 'open' AFTER 'triage_proposal';

BEGIN;

CREATE TYPE public.dispatch_task_status AS ENUM (
    'queued',
    'scheduled',
    'en_route',
    'arrived',
    'working',
    'done',
    'needs_expertise',
    'return_visit',
    'cancelled'
);

COMMENT ON TYPE public.dispatch_task_status IS
    'Task lifecycle (fieldwork). queued → scheduled → en_route → arrived → working → done | needs_expertise | return_visit; cancelled = abandoned. done/cancelled terminal.';

CREATE TABLE public.dispatch_task (
    task_id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id           integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    description          text        NOT NULL CHECK (btrim(description) <> ''),
    status               public.dispatch_task_status NOT NULL DEFAULT 'queued',
    assigned_employee_id integer     REFERENCES public.employee(employee_id),
    vendor_id            integer     REFERENCES public.vendor_contact(vendor_id),
    subcontractor_name   character varying,
    due_at               timestamptz,
    urgency_tier         text        CHECK (
                                         urgency_tier IS NULL
                                         OR urgency_tier IN ('URGENT', 'Intermédiaire', 'Faible')
                                     ),
    source               text        NOT NULL DEFAULT 'dispatcher'
                                     CHECK (source IN ('ai_recommended', 'dispatcher', 'follow_up')),
    accepted_at          timestamptz,
    parent_task_id       integer     REFERENCES public.dispatch_task(task_id),
    sort_order           smallint    NOT NULL DEFAULT 0,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.dispatch_task IS
    'Schedulable work unit under a Service Call (maintenance_request). accepted_at IS NULL = AI/dispatcher proposal awaiting accept.';
COMMENT ON COLUMN public.dispatch_task.accepted_at IS
    'NULL while an AI draft awaits dispatcher accept; hidden from tech portal and calendar until set.';
COMMENT ON COLUMN public.dispatch_task.urgency_tier IS
    'Optional override; NULL = inherit from the call. URGENT | Intermédiaire | Faible.';
COMMENT ON COLUMN public.dispatch_task.parent_task_id IS
    'Set for follow-up tasks (source = follow_up).';

CREATE INDEX dispatch_task_request_id_idx
    ON public.dispatch_task (request_id);

CREATE INDEX dispatch_task_assignee_due_idx
    ON public.dispatch_task (assigned_employee_id, due_at);

CREATE INDEX dispatch_task_status_accepted_idx
    ON public.dispatch_task (status)
    WHERE accepted_at IS NOT NULL;

ALTER TABLE public.dispatch_task ENABLE ROW LEVEL SECURITY;

-- Visit → task. Nullable until Task 5 backfills open requests; request_id stays
-- denormalized on request_visit for existing queries.
ALTER TABLE public.request_visit
    ADD COLUMN task_id integer REFERENCES public.dispatch_task(task_id);

CREATE INDEX request_visit_task_id_idx ON public.request_visit (task_id);

COMMENT ON COLUMN public.request_visit.task_id IS
    'Task this visit belongs to. Nullable until the open-request backfill; NOT NULL for new rows once enforced.';

COMMENT ON TYPE public.request_status IS
    'Service Call (maintenance_request) container lifecycle. Fieldwork (scheduled / en_route / arrived / working) lives on dispatch_task.status, not here. Always triage before fieldwork: no intake → en_route bypass. Auto-retry eligibility: only triage_pending and triage_failed are picked up by the retry loop. triage_clarify must NOT enter the loop — it signals a human-input requirement, not a transient error.

intake_received       — request landed; waiting for the next triage run.
triage_pending        — acquired by the triage service; triage_started_at is set.
triage_clarify        — BLOCKED: needs coordinator action before re-entering the queue (also where reject-all of proposed tasks lands).
triage_proposal       — triage wrote ≥1 draft dispatch_task (accepted_at IS NULL); dispatcher must accept/edit/add. First pass only.
triage_failed         — retries exhausted; auto-retry after review/reset.
triaged               — legacy: pre-task single-step accept; moves to open.
open                  — ≥1 accepted dispatch_task; work queued or in flight. Mid-life proposals stay here. Auto-closes when every accepted task is done/cancelled and no proposals remain.
closed                — all linked tasks resolved; call closed out.
scheduled             — LEGACY, do not write: pre-cutover fieldwork state; backfilled to open + dispatch_task.
awaiting_redispatch   — LEGACY, do not write: pre-cutover; backfilled to open + needs_expertise task.
en_route              — LEGACY, do not write: pre-cutover; en route is now dispatch_task.status.
arrived               — LEGACY, do not write: pre-cutover; arrived is now dispatch_task.status.';

COMMIT;

