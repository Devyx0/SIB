BEGIN;

CREATE TABLE public.request_visit (
    visit_id     integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    employee_id  integer     NOT NULL REFERENCES public.employee(employee_id),
    en_route_at  timestamptz NOT NULL DEFAULT now(),
    en_route_lat numeric,
    en_route_lng numeric,
    closeout_at  timestamptz,
    closeout_lat numeric,
    closeout_lng numeric,
    outcome      public.closeout_outcome
);

CREATE INDEX request_visit_request_id_idx ON public.request_visit (request_id);

-- One open visit per employee — the one-open-call rule as a DB constraint.
CREATE UNIQUE INDEX request_visit_one_open_idx
    ON public.request_visit (employee_id)
    WHERE closeout_at IS NULL;

ALTER TABLE public.request_visit ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.message_outbox (
    id                     integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id             integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    visit_id               integer     REFERENCES public.request_visit(visit_id),
    channel                text        NOT NULL CHECK (channel IN ('sms', 'email')),
    recipient              text,
    subject                text,
    body                   text        NOT NULL,
    status                 text        NOT NULL DEFAULT 'not_sent'
                                       CHECK (status IN ('not_sent', 'sent', 'failed')),
    created_at             timestamptz NOT NULL DEFAULT now(),
    sent_at                timestamptz,
    created_by_employee_id integer     REFERENCES public.employee(employee_id)
);

CREATE INDEX message_outbox_request_id_idx ON public.message_outbox (request_id);

ALTER TABLE public.message_outbox ENABLE ROW LEVEL SECURITY;

COMMIT;

