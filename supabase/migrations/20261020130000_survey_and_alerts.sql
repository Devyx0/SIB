-- Tenant satisfaction survey (tokenized public form) + coordinator in-app alerts.
-- No SMS/email sender — survey rows and alerts are stored for the app to use.

BEGIN;

CREATE TABLE public.satisfaction_survey (
    survey_id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token                  text        NOT NULL UNIQUE,
    request_id             integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    visit_id               integer     REFERENCES public.request_visit(visit_id),
    employee_id            integer     NOT NULL REFERENCES public.employee(employee_id),
    created_at             timestamptz NOT NULL DEFAULT now(),
    -- Answers (null until submitted)
    polite                 boolean,
    satisfied              boolean,
    problem_solved         boolean,
    comments               text,
    submitted_at           timestamptz
);

CREATE INDEX satisfaction_survey_request_id_idx ON public.satisfaction_survey (request_id);
CREATE INDEX satisfaction_survey_employee_id_idx ON public.satisfaction_survey (employee_id);

ALTER TABLE public.satisfaction_survey ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.coordinator_alert (
    alert_id               integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id             integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    kind                   text        NOT NULL
        CHECK (kind IN (
            'call_completed',
            'tech_log',
            'followup_added',
            'expertise_needed'
        )),
    summary                text        NOT NULL,
    created_at             timestamptz NOT NULL DEFAULT now(),
    read_at                timestamptz,
    read_by_employee_id    integer     REFERENCES public.employee(employee_id)
);

CREATE INDEX coordinator_alert_unread_idx
    ON public.coordinator_alert (created_at DESC)
    WHERE read_at IS NULL;

CREATE INDEX coordinator_alert_request_id_idx ON public.coordinator_alert (request_id);

ALTER TABLE public.coordinator_alert ENABLE ROW LEVEL SECURITY;

COMMIT;

