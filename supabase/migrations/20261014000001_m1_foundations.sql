DO $$
DECLARE v_count bigint;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM public.maintenance_request
    WHERE submission_date IS NOT NULL;
    IF v_count > 0 THEN
        RAISE EXCEPTION
            'submission_date guard: % non-NULL row(s) found — ALTER TYPE aborted',
            v_count;
    END IF;
END $$;

