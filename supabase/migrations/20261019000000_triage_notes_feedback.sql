BEGIN;

-- ── Enum ──────────────────────────────────────────────────────────────────────

CREATE TYPE public.triage_feedback_level AS ENUM (
    'utile',
    'partiellement utile',
    'pas utile'
);

-- ── Table ─────────────────────────────────────────────────────────────────────
--
-- triage_output / triage_model_version: snapshot of the triage output at the
--   time of the LAST write (always current state). The old snapshot before each
--   edit is preserved inside edit_history entries.
--
-- edit_history: jsonb array of objects with 8 fields:
--   edited_at, edited_by, old_level, new_level, old_reason, new_reason,
--   old_triage_output, old_triage_model_version
--   An entry is only appended when at least one of level, reason, or
--   triage_output changes (no-op edits produce no history entry).
--
-- UNIQUE (request_id, employee_id): one feedback row per employee per call;
--   also serves as the primary lookup index — no redundant index added.

CREATE TABLE public.triage_notes_feedback (
    feedback_id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id           integer     NOT NULL REFERENCES public.maintenance_request(request_id),
    employee_id          integer     NOT NULL REFERENCES public.employee(employee_id),
    level                public.triage_feedback_level NOT NULL,
    reason               text,
    triage_output        jsonb       NOT NULL,
    triage_model_version varchar     NOT NULL,
    edit_history         jsonb       NOT NULL DEFAULT '[]',
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tnf_unique_per_employee UNIQUE (request_id, employee_id)
);

-- RLS enabled; no policies. Access is through FastAPI / service_role only.
-- Pattern matches decision_justification_log (same owner, same RLS setting, no
-- anon/authenticated policies). REVOKE on the view below makes the isolation
-- explicit even though no policies would allow those roles through anyway.
ALTER TABLE public.triage_notes_feedback ENABLE ROW LEVEL SECURITY;


-- ── Developer-only view ───────────────────────────────────────────────────────
--
-- security_invoker = true: the view executes with the querier's own privileges,
--   not the owner's. An anon/authenticated user querying the view is checked
--   against THEIR OWN grants on the underlying table (which have none), so
--   they are denied even before the REVOKE below.
-- REVOKE makes the intent explicit and removes any default inherited privileges.
-- This view is not registered on the FastAPI router.

CREATE VIEW public.triage_feedback_review
    WITH (security_invoker = true)
    AS
    SELECT
        mr.request_id,
        mr.raw_title                AS title,
        tnf.triage_output           AS snapshot,
        tnf.level::text             AS level,
        tnf.reason,
        e.nom_employe               AS employee,
        tnf.created_at,
        tnf.updated_at
    FROM public.triage_notes_feedback tnf
    JOIN public.maintenance_request mr ON mr.request_id = tnf.request_id
    JOIN public.employee            e  ON e.employee_id  = tnf.employee_id;

REVOKE ALL ON public.triage_feedback_review FROM anon, authenticated;

COMMIT;


